// Where-strategy oracle prep (#216, lane B1): a second disposable copy of
// the canonical fixture — same canonical bytes, generated config carrying
// `scopedStyleStrategy: 'where'` — because the where-compiled form of scoped
// selectors (`.hero-title:where(.astro-<hash>)` — the scoped CLASS, carrying
// the same path-derived hash the attribute strategy's `data-astro-cid-*`
// form uses) is a frozen contract cell (#216 AC-2) the default
// attribute-strategy oracle cannot produce. The frozen truth is
// css-index.where.json, enforced by CID_FORM in the schema and the capture
// guard in live-capture.ts; on any conflict, trust the corpus and the
// guards, never a comment — regenerate instead of "correcting" toward prose.
// Reuses the shared oracle machinery from scripts/oracle.mjs verbatim; the
// only difference from the main prep is the generated astro.config.mjs and
// the output dir (gitignored via this folder's .gitignore).
//
// The where lane's port: ASTROIX_E2E_WHERE_PORT, owned (default, rationale,
// and all) by e2e/ports.ts beside the main/pack/src trio; the boot side in
// oracle-server.ts always exports the var, so the baked default below only
// serves manual `npm run dev` in the generated dir.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  assertOracleLink,
  copyOracleSources,
  ensureFreshDist,
  ensurePlainFixtureInstall,
  evictStaleFixtureIntegration,
  farmNodeModules,
  resetOracle,
  root,
  syncStaging,
  writeOracleMeta,
} from '../../scripts/oracle.mjs';

const staging = join(root, '.astroix-local');
const whereOracle = join(root, 'e2e', 'contract-oracle', '.oracle-where');

const WHERE_ORACLE_CONFIG = `import astroix from '@wojciechpiskorz/astroix';
import { defineConfig } from 'astro/config';

// Disposable where-strategy oracle copy generated by
// e2e/contract-oracle/prepare-where-oracle.mjs (#216): canonical fixture
// bytes, the retired integration, and the 'where' scopedStyleStrategy whose
// compiled selector form the inspection contracts freeze.
export default defineConfig({
  scopedStyleStrategy: 'where',
  integrations: [astroix()],
});
`;

ensureFreshDist();
syncStaging(staging);
ensurePlainFixtureInstall();
evictStaleFixtureIntegration();

resetOracle(whereOracle);
copyOracleSources(whereOracle, join(root, 'e2e', 'fixture'));
writeOracleMeta(whereOracle, {
  name: 'astroix-e2e-oracle-where',
  scripts: {
    dev: 'astro dev --ignore-lock --port ${ASTROIX_E2E_WHERE_PORT:-4395}',
    build: 'astro build',
  },
});
writeFileSync(join(whereOracle, 'astro.config.mjs'), WHERE_ORACLE_CONFIG);
farmNodeModules(whereOracle, staging);
assertOracleLink(whereOracle);
console.log(`[astroix] where-strategy oracle ready at ${whereOracle}`);
